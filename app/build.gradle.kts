// The TMDB key lives in local.properties, which git ignores, so it never
// reaches the repository. Anyone cloning this adds their own.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
val tmdbApiKey: String = localProperties.getProperty("tmdbApiKey") ?: ""

